"""Exploratory data analysis for the cleaned NASA C-MAPSS FD001 dataset."""

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA_FILE = ROOT / "data" / "processed" / "train_FD001_clean.csv"
REPORT_DIR = ROOT / "reports"
PLOT_DIR = REPORT_DIR / "eda_plots"

REPORT_DIR.mkdir(parents=True, exist_ok=True)
PLOT_DIR.mkdir(parents=True, exist_ok=True)

if not DATA_FILE.exists():
    raise FileNotFoundError(f"Cleaned dataset not found: {DATA_FILE}")

df = pd.read_csv(DATA_FILE)

required = {"engine_id", "cycle"}
missing = required - set(df.columns)
if missing:
    raise ValueError(f"Missing required columns: {sorted(missing)}")

sensor_cols = [c for c in df.columns if c.startswith("sensor_")]
setting_cols = [c for c in df.columns if c.startswith("setting_")]
feature_cols = setting_cols + sensor_cols

if not sensor_cols:
    raise ValueError("No sensor columns found in the cleaned CSV.")

# 1. Basic dataset overview
n_rows, n_cols = df.shape
n_engines = df["engine_id"].nunique()
missing_cells = int(df.isna().sum().sum())
duplicate_rows = int(df.duplicated().sum())
duplicate_engine_cycles = int(df.duplicated(["engine_id", "cycle"]).sum())

engine_lengths = df.groupby("engine_id")["cycle"].agg(["min", "max", "count"])
constant_features = [
    col for col in feature_cols
    if df[col].nunique(dropna=True) <= 1
]

# 2. Descriptive statistics
stats = df[feature_cols].describe().T
stats["missing_count"] = df[feature_cols].isna().sum()
stats["unique_count"] = df[feature_cols].nunique(dropna=True)
stats.to_csv(REPORT_DIR / "eda_feature_summary.csv")

# 3. IQR outlier screening
# This is a screening method, not proof that an observation is erroneous.
outlier_rows = []
for col in feature_cols:
    values = df[col].dropna()
    if values.empty:
        continue
    q1 = values.quantile(0.25)
    q3 = values.quantile(0.75)
    iqr = q3 - q1
    lower = q1 - 1.5 * iqr
    upper = q3 + 1.5 * iqr
    count = int(((values < lower) | (values > upper)).sum())
    outlier_rows.append({
        "feature": col,
        "q1": q1,
        "q3": q3,
        "iqr": iqr,
        "lower_bound": lower,
        "upper_bound": upper,
        "outlier_count": count,
        "outlier_percent": 100 * count / len(values),
    })

outliers = pd.DataFrame(outlier_rows)
outliers.to_csv(REPORT_DIR / "eda_iqr_outlier_screening.csv", index=False)

# 4. Feature correlation matrix
correlations = df[feature_cols].corr(numeric_only=True)
correlations.to_csv(REPORT_DIR / "eda_feature_correlations.csv")

fig, ax = plt.subplots(figsize=(16, 13))
image = ax.imshow(correlations, cmap="coolwarm", vmin=-1, vmax=1, aspect="auto")
ax.set_xticks(range(len(correlations.columns)))
ax.set_xticklabels(correlations.columns, rotation=90, fontsize=7)
ax.set_yticks(range(len(correlations.index)))
ax.set_yticklabels(correlations.index, fontsize=7)
ax.set_title("FD001 Training Data: Feature Correlation Matrix")
fig.colorbar(image, ax=ax, label="Pearson correlation")
fig.tight_layout()
fig.savefig(PLOT_DIR / "feature_correlation_matrix.png", dpi=160)
plt.close(fig)

# 5. Sensor distributions
ncols = 3
nrows = int(np.ceil(len(sensor_cols) / ncols))
fig, axes = plt.subplots(nrows, ncols, figsize=(15, 3.2 * nrows))
axes = np.array(axes).reshape(-1)

for ax, col in zip(axes, sensor_cols):
    ax.hist(df[col].dropna(), bins=40)
    ax.set_title(col)
    ax.set_xlabel("Value")
    ax.set_ylabel("Frequency")

for ax in axes[len(sensor_cols):]:
    ax.set_visible(False)

fig.suptitle("FD001 Training Data: Sensor Distributions", y=1.01)
fig.tight_layout()
fig.savefig(PLOT_DIR / "sensor_distributions.png", dpi=160, bbox_inches="tight")
plt.close(fig)

# 6. Mean sensor trends across engine cycles.
# These are cross-engine averages; they are not individual engine trajectories.
trend = df.groupby("cycle")[sensor_cols].mean()
trend.to_csv(REPORT_DIR / "eda_mean_sensor_trends.csv")

ncols = 3
nrows = int(np.ceil(len(sensor_cols) / ncols))
fig, axes = plt.subplots(nrows, ncols, figsize=(15, 3.2 * nrows))
axes = np.array(axes).reshape(-1)

for ax, col in zip(axes, sensor_cols):
    ax.plot(trend.index, trend[col], linewidth=1)
    ax.set_title(col)
    ax.set_xlabel("Cycle")
    ax.set_ylabel("Mean sensor value")

for ax in axes[len(sensor_cols):]:
    ax.set_visible(False)

fig.suptitle("FD001 Training Data: Mean Sensor Values by Cycle", y=1.01)
fig.tight_layout()
fig.savefig(PLOT_DIR / "mean_sensor_trends.png", dpi=160, bbox_inches="tight")
plt.close(fig)

# 7. Report key findings directly from the loaded CSV.
report = f"""# FD001 Exploratory Data Analysis

Generated by `notebooks/01_eda_fd001.py` from `{DATA_FILE.relative_to(ROOT)}`.

## Dataset overview

- Rows: {n_rows:,}
- Columns: {n_cols}
- Unique engines: {n_engines}
- Missing cells: {missing_cells}
- Duplicate full rows: {duplicate_rows}
- Duplicate engine-cycle pairs: {duplicate_engine_cycles}
- Engine cycle range across engines: {int(engine_lengths['min'].min())} to {int(engine_lengths['max'].max())}
- Median observed rows per engine: {engine_lengths['count'].median():.1f}

## Feature quality

- Settings analyzed: {len(setting_cols)}
- Sensors analyzed: {len(sensor_cols)}
- Constant settings/sensors: {', '.join(constant_features) if constant_features else 'None detected'}

Constant features have no variation in this training file and may provide little predictive value.
Confirm this finding against validation/test data before deciding whether to remove a feature.

## Outlier screening

The IQR rule flags values below Q1 - 1.5 × IQR or above Q3 + 1.5 × IQR.
Flagged observations are candidates for investigation, not automatically errors or values to delete.
See `eda_iqr_outlier_screening.csv`.

## Correlation analysis

See `eda_feature_correlations.csv` and `eda_plots/feature_correlation_matrix.png`.
Correlations describe linear association, not causation. Highly correlated features may contain
overlapping information, but feature removal should be decided using training-only analysis
and validation results.

## Sensor behaviour

- `eda_plots/sensor_distributions.png` shows each sensor's value distribution.
- `eda_plots/mean_sensor_trends.png` shows average sensor values at each observed cycle.

Mean trends combine engines that may have different lifetimes. They are exploratory summaries,
not proof that an individual engine follows the same trajectory.

## Outputs

- `eda_feature_summary.csv`
- `eda_iqr_outlier_screening.csv`
- `eda_feature_correlations.csv`
- `eda_mean_sensor_trends.csv`
- `eda_plots/feature_correlation_matrix.png`
- `eda_plots/sensor_distributions.png`
- `eda_plots/mean_sensor_trends.png`

## Limitations

This analysis uses the cleaned training CSV only. It does not compare train and test distributions,
establish sensor physical meanings, create target labels, or train a predictive model.
"""

(REPORT_DIR / "eda_findings.md").write_text(report, encoding="utf-8")

print("EDA completed successfully.")
print(f"Dataset shape: {df.shape}")
print(f"Engines: {n_engines}")
print(f"Missing cells: {missing_cells}")
print(f"Duplicate rows: {duplicate_rows}")
print(f"Duplicate engine-cycle pairs: {duplicate_engine_cycles}")
print("Constant features:", constant_features)
print(f"Report saved: {REPORT_DIR / 'eda_findings.md'}")
print(f"Plots saved: {PLOT_DIR}")
